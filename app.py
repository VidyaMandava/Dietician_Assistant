# Text extraction and processing functions
def extract_text_from_pdfs(pdf_dir="diet_pdfs"):
    """Extract text from all PDFs in the specified directory"""
    # Get all PDF files in the directory
    pdf_files = glob.glob(os.path.join(pdf_dir, "*.pdf"))

    if not pdf_files:
        # If no PDFs found, use sample data
        print("No PDF files found. Using sample data.")
        return generate_sample_data()

    print(f"Found {len(pdf_files)} PDF files: {[os.path.basename(f) for f in pdf_files]}")

    # Dictionary to store extracted text from each PDF
    extracted_texts = {}

    # Process each PDF file
    for pdf_path in pdf_files:
        try:
            pdf_reader = PdfReader(pdf_path)
            text = ""
            for page in pdf_reader.pages:
                text += page.extract_text()

            # Store text with filename as key
            filename = os.path.basename(pdf_path)
            extracted_texts[filename] = text
            print(f"Successfully extracted text from {filename}, {len(text)} characters")
        except Exception as e:
            print(f"Error extracting text from {os.path.basename(pdf_path)}: {str(e)}")

    return extracted_texts

