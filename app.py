def get_recipe(recipe_name):
    """Get recipe preparation instructions for a specific dish"""
    try:
        # Create a new OpenAI client instance
        client = OpenAI(api_key=OPENAI_API_KEY)

        # Create a prompt for recipe preparation
        RECIPE_PROMPT = f"""
        You are a helpful culinary assistant who provides detailed recipe instructions.
        Provide a detailed recipe for preparing {recipe_name}. Include:

        1. List of ingredients with measurements
        2. Step-by-step preparation instructions
        3. Approximate cooking time
        4. Nutrition information if available
        5. Any tips for dietary modifications
        """

        # Call the OpenAI API to generate the recipe
        response = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": "You are a helpful culinary assistant."},
                {"role": "user", "content": RECIPE_PROMPT}
            ],
            max_tokens=800,
            temperature=0.7
        )

        # Check if the response contains the expected fields
        if response and hasattr(response, 'choices') and len(response.choices) > 0:
            return response.choices[0].message.content
        else:
            return "Sorry, I couldn't generate a recipe. Please try again."

    except Exception as e:
        print(f"Error in get_recipe: {str(e)}")
        return f"Error generating recipe: {str(e)}"

# Gradio UI Class
class DieticianAssistantUI:
    def __init__(self, vector_store, rag_chains):
        self.vector_store = vector_store
        self.rag_chains = rag_chains
        self.openai_api_key = OPENAI_API_KEY

        # Create a directory for saved plans if it doesn't exist
        self.save_dir = "saved_meal_plans"
        if not os.path.exists(self.save_dir):
            os.makedirs(self.save_dir)

        # Initialize history storage
        self.history_file = os.path.join(self.save_dir, "request_history.json")
        if os.path.exists(self.history_file):
            with open(self.history_file, 'r') as f:
                self.history = json.load(f)
        else:
            self.history = {
                "toddler_plans": [],
                "adult_plans": [],
                "nutrition_queries": [],
                "recipe_queries": []
            }
            self._save_history()

    def _save_history(self):
        """Save history to file"""
        with open(self.history_file, 'w') as f:
            json.dump(self.history, f, indent=2)

    def _add_to_history(self, category, query, content=None, timestamp=None):
        """Add an item to history with content"""
        if timestamp is None:
            timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        # Store first line of content as preview
        preview = ""
        if content:
            # First line only for preview
            first_line = content.split('\n')[0] if '\n' in content else content
            preview = first_line

        self.history[category].append({
            "query": query,
            "timestamp": timestamp,
            "preview": preview
        })

        if len(self.history[category]) > 10:  # Keep only last 10 items
            self.history[category] = self.history[category][-10:]
        self._save_history()

    def _get_history_text(self):
        """Generate formatted history text"""
        history_text = "# Recent Request History\n\n"

        if self.history["toddler_plans"]:
            history_text += "## Toddler Meal Plans\n"
            for item in reversed(self.history["toddler_plans"]):
                preview = item.get('preview', '')
                if preview:
                    history_text += f"- {item['timestamp']}: Generated toddler meal plan\n  *Preview: {preview}*\n\n"
                else:
                    history_text += f"- {item['timestamp']}: Generated toddler meal plan\n\n"

        if self.history["adult_plans"]:
            history_text += "## Adult Weight Loss Plans\n"
            for item in reversed(self.history["adult_plans"]):
                preview = item.get('preview', '')
                if preview:
                    history_text += f"- {item['timestamp']}: Generated adult weight loss plan\n  *Preview: {preview}*\n\n"
                else:
                    history_text += f"- {item['timestamp']}: Generated adult weight loss plan\n\n"

        if self.history["nutrition_queries"]:
            history_text += "## Nutrition Queries\n"
            for item in reversed(self.history["nutrition_queries"]):
                preview = item.get('preview', '')
                if preview:
                    history_text += f"- {item['timestamp']}: {item['query']}\n  *Preview: {preview}*\n\n"
                else:
                    history_text += f"- {item['timestamp']}: {item['query']}\n\n"

        if self.history["recipe_queries"]:
            history_text += "## Recipe Queries\n"
            for item in reversed(self.history["recipe_queries"]):
                preview = item.get('preview', '')
                if preview:
                    history_text += f"- {item['timestamp']}: {item['query']}\n  *Preview: {preview}*\n\n"
                else:
                    history_text += f"- {item['timestamp']}: {item['query']}\n\n"

        return history_text

    def generate_toddler_plan(self):
        """Generate weekly diet plan for toddler"""
        # Simple text output to show processing
        time.sleep(0.5)  # Small delay to show the message is updating
        processing_message = "⏳ Generating toddler meal plan... This may take a minute."
        yield processing_message

        # Generate the plan
        plan = generate_weekly_diet_plan(self.rag_chains, "toddler")

        # Save to history with content
        self._add_to_history("toddler_plans", "Toddler meal plan", plan)

        # Return the complete plan
        yield plan

    def generate_adult_plan(self):
        """Generate weekly diet plan for adults"""
        # Simple text output to show processing
        time.sleep(0.5)  # Small delay to show the message is updating
        processing_message = "⏳ Generating adult weight loss meal plan... This may take a minute."
        yield processing_message

        # Generate the plan
        plan = generate_weekly_diet_plan(self.rag_chains, "adult")

        # Save to history with content
        self._add_to_history("adult_plans", "Adult weight loss plan", plan)

        # Return the complete plan
        yield plan

    def get_nutrition_info(self, recipe_name):
        """Get nutritional information for a specific recipe"""
        if not recipe_name or recipe_name.strip() == "":
            yield "Please enter a recipe name."
            return

        # Simple text output to show processing
        time.sleep(0.5)  # Small delay to show the message is updating
        processing_message = f"⏳ Analyzing nutrition for {recipe_name}... This may take a minute."
        yield processing_message

        # Get the information
        info = get_recipe_nutrition(self.rag_chains, recipe_name)

        # Save to history with content
        self._add_to_history("nutrition_queries", recipe_name, info)

        # Return the complete information
        yield info

    def get_recipe_instructions(self, recipe_name):
        """Get recipe preparation instructions"""
        if not recipe_name or recipe_name.strip() == "":
            yield "Please enter a dish name."
            return

        # Simple text output to show processing
        time.sleep(0.5)  # Small delay to show the message is updating
        processing_message = f"⏳ Preparing recipe for {recipe_name}... This may take a minute."
        yield processing_message

        try:
            # Get recipe using the standalone function
            recipe = get_recipe(recipe_name)

            # Save to history with content
            self._add_to_history("recipe_queries", recipe_name, recipe)

            yield recipe
        except Exception as e:
            yield f"Error generating recipe: {str(e)}"

    def refresh_history(self):
        """Refresh the history display"""
        return self._get_history_text()

