def clean_text(text):
    """Clean and preprocess the extracted text"""
    # Remove extra whitespaces
    text = re.sub(r'\s+', ' ', text)
    # Remove special characters that aren't relevant
    text = re.sub(r'[^\w\s.,;:()-]', '', text)
    return text.strip()

def split_text_into_chunks(text, chunk_size=1000, chunk_overlap=200):
    """Split text into overlapping chunks"""
    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=chunk_size,
        chunk_overlap=chunk_overlap,
        length_function=len
    )
    chunks = text_splitter.split_text(text)
    return chunks

def create_vector_store(collection_name="dietician-assistant", pdf_dir="diet_pdfs"):
    """Create a vector store from PDFs using ChromaDB"""
    # Extract text from all PDFs in the directory
    extracted_texts = extract_text_from_pdfs(pdf_dir)

    all_chunks = []
    all_metadata = []

    # Process each extracted text
    chunk_id_counter = 0
    for filename, text in extracted_texts.items():
        cleaned_text = clean_text(text)
        chunks = split_text_into_chunks(cleaned_text)

        for i, chunk in enumerate(chunks):
            all_chunks.append(chunk)
            all_metadata.append({"source": filename, "chunk_id": i})
            chunk_id_counter += 1

    print(f"Created {len(all_chunks)} chunks from all PDFs/sample data")

    # Initialize embeddings for LangChain
    embeddings = OpenAIEmbeddings(model="text-embedding-3-small")

    # Set up ChromaDB persistent directory
    persist_directory = "chroma_db"

    # Create Chroma vector store from the documents (LangChain interface)
    print(f"Uploading {len(all_chunks)} chunks to ChromaDB...")
    try:
        # Create the vector store
        vector_store = Chroma.from_texts(
            texts=all_chunks,
            embedding=embeddings,
            metadatas=all_metadata,
            persist_directory=persist_directory
        )

        # Persist the vector store to disk
        vector_store.persist()

        print("Vector store creation complete!")
        return vector_store

    except Exception as e:
        print(f"Error creating vector store: {str(e)}")
        raise

def setup_rag_model(vector_store):
    """Set up the RAG model with appropriate prompts"""
    # Create LLM
    chatgpt = ChatOpenAI(model_name='gpt-4o-mini', temperature=0)

    # Create memory
    memory = ConversationBufferMemory(
        memory_key="chat_history",
        return_messages=True
    )

    # Create the prompt template for different use cases
    toddler_diet_template = """
    You are a professional pediatric nutritionist specializing in Indian cuisine.
    Use the following information from the nutritional database and your own knowledge to create tailored weekly nutrition plan for a 4-year-old toddler.
    Consider the child's nutritional needs for growth and development.

    Context information from nutrition database: {context}

    Include:
    - Breakfast, Brunch, Lunch, Snacks, Dinner
    - Day-wise plan
    - Calories per meal (approx)

    Chat History: {chat_history}

    Question: {question}
    """

    adult_diet_template = """
    You are a professional nutritionist specializing in Indian cuisine and weight loss.
    Use the following information from the nutritional database and your own knowledge, to create a weekly weight loss diet plan for adults aged 36 and 42
    who want to lose weight while maintaining proper nutrition.

    Context information from nutrition database: {context}

    Include:
    - Breakfast, Lunch, Snacks, Dinner
    - Day-wise plan
    - Calories per meal (approx)
    - Balance of protein, fiber, and carbs

    Chat History: {chat_history}

    Question: {question}

    Return the output as a markdown table.
    """

    # Create the prompt templates
    TODDLER_PROMPT = PromptTemplate(
        input_variables=["context", "chat_history", "question"],
        template=toddler_diet_template,
    )

    ADULT_PROMPT = PromptTemplate(
        input_variables=["context", "chat_history", "question"],
        template=adult_diet_template,
    )

    # Create the RAG chain for toddler
    toddler_qa_chain = ConversationalRetrievalChain.from_llm(
        llm=chatgpt,
        retriever=vector_store.as_retriever(search_kwargs={"k": 5}),
        memory=memory,
        combine_docs_chain_kwargs={"prompt": TODDLER_PROMPT}
    )

    # Create the RAG chain for adults
    adult_qa_chain = ConversationalRetrievalChain.from_llm(
        llm=chatgpt,
        retriever=vector_store.as_retriever(search_kwargs={"k": 5}),
        memory=memory,
        combine_docs_chain_kwargs={"prompt": ADULT_PROMPT}
    )

    return {
        "toddler": toddler_qa_chain,
        "adult": adult_qa_chain
    }

# Function to generate diet plans
def generate_diet_plan(rag_chains, user_type, query):
    """Generate diet plan based on user query"""
    if user_type not in rag_chains:
        return "Invalid user type. Please choose 'toddler' or 'adult'."

    chain = rag_chains[user_type]
    response = chain({"question": query})
    return response["answer"]

# Create a function to generate a weekly diet plan
def generate_weekly_diet_plan(rag_chains, user_type):
    """Generate a complete weekly diet plan"""
    if user_type == "toddler":
        query = """
        Create a detailed 7-day Indian diet plan for a 4-year-old toddler in tabular format with the following structure:
        1. For each day, include breakfast, mid-morning snack, lunch, evening snack, and dinner
        2. For each meal, specify portion sizes appropriate for a 4-year-old
        3. Ensure variety and balanced nutrition with focus on growth and development
        4. Include information about essential nutrients included in each day's plan
        5. Suggest creative ways to make meals appealing for children
        6. Avoid cheese cubes.
        7. Lunch should contain roti or rice or both roti and rice.
        Use the Indian recipes when possible.
        """
    else:  # adult
        query = """
        Create a detailed 7-day Indian weight loss diet plan for adults (36 and 42 years old) in tabular format with the following structure:
        1. For each day, include breakfast, mid-morning snack, lunch, evening snack, and dinner
        2. For each meal, specify portion sizes and approximate calorie counts
        3. Ensure variety and balanced nutrition with focus on weight loss
        4. Include information about macronutrient distribution (protein, carbs, fats)
        5. Suggest meal prep tips to make following the plan easier
        Use the Indian recipes when possible.
        """

    return generate_diet_plan(rag_chains, user_type, query)

# Function to process nutritional information for specific recipes
def get_recipe_nutrition(rag_chains, recipe_name):
    """Get nutritional information for a specific recipe"""
    query = f"Provide detailed nutritional information for the recipe '{recipe_name}', including calories, proteins, carbohydrates, fats, and essential vitamins and minerals."

    # Use the adult chain for recipe queries as it's more comprehensive
    response = generate_diet_plan(rag_chains, "adult", query)
